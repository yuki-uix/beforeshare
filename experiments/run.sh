#!/usr/bin/env bash
# Regenerates results.tsv. Both probes, same fixtures, same questions, one run.
set -euo pipefail
cd "$(dirname "$0")"
# The probe sources are hashed into the file. Without this, editing a probe and
# not re-running leaves a results file that still satisfies every check - the
# ADR is verified against these numbers, and these numbers were verified against
# nothing.
probes=$(cat pdf-parser-bakeoff/src/main.rs pdf-parser-bakeoff/Cargo.toml              mupdf-probe/src/main.rs mupdf-probe/Cargo.toml | shasum -a 256 | cut -d' ' -f1)
{
  echo "# Regenerated by experiments/run.sh on a machine, not copied by hand."
  echo "# probes-sha256 $probes"
  echo "# lopdf $(grep -m1 '^lopdf' pdf-parser-bakeoff/Cargo.toml)"
  echo "# mupdf $(grep -m1 '^mupdf' mupdf-probe/Cargo.toml)"
  echo
  (cd pdf-parser-bakeoff && cargo run --quiet 2>/dev/null)
  echo
  (cd mupdf-probe && cargo run --quiet 2>/dev/null)
} > results.tsv
echo "wrote experiments/results.tsv"
