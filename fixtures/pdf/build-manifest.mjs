/**
 * The manifest, generated from the fixtures rather than maintained beside them.
 *
 * §16.2 asks for nine things per fixture. Eight of them are statements the
 * generator already makes - the label, what it means, how it was made, what the
 * detector should do with it - so writing them twice would be two things that
 * drift. The ninth, the hash, cannot be written by hand at all.
 */
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { FIXTURES, generateAll, EVAL_VERSION } from './generate.mjs';

const KIND_MEANS = {
  must_detect: 'carries the disclosure this category names; a detector that misses it is a release blocker under §17.1',
  clean_control: 'resembles the positive without carrying the disclosure; a blocking deterministic finding here is one of §17.1\'s zero cases',
};

export function buildManifest(directory) {
  const written = generateAll(directory);
  const fixtures = {};
  for (const w of written) {
    const spec = FIXTURES[w.category];
    fixtures[w.file] = {
      label: `${spec.short}.${w.kind}`,
      labelDefinition: `§7.1 — ${w.category}. ${KIND_MEANS[w.kind]}`,
      generatedBy: 'fixtures/pdf/generate.mjs, raw PDF syntax, deterministic and uncompressed',
      sha256: w.sha256,
      annotationInstructions: spec.annotationInstructions,
      expectedCoverage: w.kind === 'must_detect' ? spec.expectedCoverage : 'completed',
      expectedRemediation: w.kind === 'must_detect' ? (spec.expectedRemediation ?? 'none') : 'none',
      expectedStatus: w.kind === 'must_detect' ? spec.expectedStatus : 'no_findings',
      evalVersion: EVAL_VERSION,
      bytes: w.bytes,
    };
  }
  return {
    $comment: 'Generated by fixtures/pdf/build-manifest.mjs. §16.2 requires nine things per fixture; tools/test-fixtures.mjs checks all nine are present and that the hash is the file\'s actual hash, so a fixture edited by hand fails rather than quietly becoming its own label.',
    schemaVersion: '1.0',
    evalVersion: EVAL_VERSION,
    fixtures,
  };
}

const isMain = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;
if (isMain) {
  const dir = new URL('./files/', import.meta.url).pathname;
  const manifest = buildManifest(dir);
  const out = new URL('./manifest.json', import.meta.url).pathname;
  writeFileSync(out, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`${Object.keys(manifest.fixtures).length} fixtures in ${out}`);
}
